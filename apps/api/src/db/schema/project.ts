import { boolean, index, int, json, mysqlTable, text, timestamp, tinyint, varchar } from 'drizzle-orm/mysql-core'
import { createInsertSchema, createSelectSchema } from 'drizzle-typebox'
import { t } from 'elysia'

export const projects = mysqlTable('projects', {
  id: int('id').primaryKey().autoincrement(),
  userId: varchar('user_id', { length: 255 }).notNull(),
  status: tinyint('status').notNull().default(0),
  likeCount: int('like_count').notNull().default(0),
  name: varchar('name', { length: 255 }).notNull(),
  tagline: varchar('tagline', { length: 255 }),
  coverUrl: varchar('cover_url', { length: 255 }),
  demoImages: json('demo_images').$type<string[]>(),
  demoVideoUrl: varchar('demo_video_url', { length: 255 }),
  demoLink: varchar('demo_link', { length: 255 }),
  stage: tinyint('stage'),
  categories: json('categories').$type<string[]>(),
  problemStatement: text('problem_statement'),
  progress: text('progress'),
  nextSteps: text('next_steps'),
  differentiation: varchar('differentiation', { length: 255 }),
  businessModel: varchar('business_model', { length: 255 }),
  userCount: int('user_count'),
  monthlyRevenue: int('monthly_revenue'),
  retentionRate: int('retention_rate'),
  seekingSkills: json('seeking_skills').$type<string[]>(),
  isOpenForBeta: boolean('is_open_for_beta'),
  betaDescription: text('beta_description'),
  contactName: varchar('contact_name', { length: 255 }),
  contactPhone: varchar('contact_phone', { length: 255 }),
  contactEmail: varchar('contact_email', { length: 255 }),
  contactWechat: varchar('contact_wechat', { length: 255 }),
  teamName: varchar('team_name', { length: 255 }),
  createdAt: timestamp('created_at').notNull().defaultNow(),
  updatedAt: timestamp('updated_at').notNull().defaultNow().onUpdateNow(),
}, (table) => [
  index('idx_projects_user_id').on(table.userId),
  index('idx_projects_status').on(table.status),
  index('idx_projects_stage').on(table.stage),
])

export const InsertProject = createInsertSchema(projects, {
  id: undefined,
  createdAt: undefined,
  updatedAt: undefined,
  name: (schema) => t.String({ ...schema, minLength: 1, description: 'Project name' }),
  tagline: (s) => { s.description = 'One-line project tagline'; return s },
  coverUrl: (s) => { s.description = 'Cover image URL'; return s },
  demoImages: t.Optional(t.Union([t.Array(t.String()), t.Null()], { description: 'Demo screenshot URLs' })),
  demoVideoUrl: (s) => { s.description = 'Demo video URL (http(s) link, e.g. Bilibili/YouTube)'; return s },
  demoLink: (s) => { s.description = 'Live demo or product link'; return s },
  stage: (s) => { s.description = 'Product stage: 0=Idea, 1=Prototype, 2=Mvp, 3=Launched, 4=Revenue'; return s },
  categories: t.Optional(t.Union([t.Array(t.String()), t.Null()], { description: 'Product categories' })),
  problemStatement: (s) => { s.description = 'Who the project serves and what problem it solves'; return s },
  progress: (s) => { s.description = 'Current development progress'; return s },
  nextSteps: (s) => { s.description = 'Planned next steps'; return s },
  differentiation: (s) => { s.description = 'One-line differentiation from existing solutions'; return s },
  businessModel: (s) => { s.description = 'How the project makes money'; return s },
  userCount: (s) => { s.description = 'Current user count (traction)'; return s },
  monthlyRevenue: (s) => { s.description = 'Monthly revenue in CNY (traction)'; return s },
  retentionRate: (s) => { s.description = '30-day retention rate in percent 0-100 (traction)'; return s },
  seekingSkills: t.Optional(t.Union([t.Array(t.String()), t.Null()], { description: 'Skills the project is looking for (from TALENT_SKILLS)' })),
  isOpenForBeta: (s) => { s.description = 'Whether beta testing is open'; return s },
  betaDescription: (s) => { s.description = 'Beta program description (required when isOpenForBeta is true)'; return s },
  contactName: (s) => { s.description = 'Contact person name'; return s },
  contactPhone: (s) => { s.description = 'Contact phone number (private)'; return s },
  contactEmail: (s) => { s.description = 'Contact email address (private)'; return s },
  contactWechat: (s) => { s.description = 'Contact WeChat ID (private)'; return s },
  teamName: (s) => { s.description = 'Team or company name'; return s },
})
export type InsertProject = typeof InsertProject.static

